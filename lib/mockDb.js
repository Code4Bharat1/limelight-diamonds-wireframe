// ─── Stock Movements Ledger ──────────────────────────────────────────────────
export function buildMovement({
  type,
  productId,
  quantity,
  fromWarehouseId,
  toWarehouseId,
  storeId,
  supplierId,
  customerId,
  performedById,
  reason,
  notes,
  referenceNo,
  unitPrice,
  disposition,
  source,
  createdAt,
}) {
  const p = productRef(productId);
  const price = unitPrice ?? (['incoming'].includes(type) ? p?.purchasePrice : p?.sellingPrice);
  return {
    _id: newId('mv'),
    type,
    product: p,
    quantity,
    fromWarehouse: fromWarehouseId ? whRef(fromWarehouseId) : null,
    toWarehouse: toWarehouseId ? whRef(toWarehouseId) : null,
    store: storeId ? storeRef(storeId) : null,
    supplier: supplierId ? sRef(supplierId) : null,
    customer: customerId ? cRef(customerId) : null,
    performedBy: userRef(performedById),
    reason,
    notes,
    referenceNo,
    disposition,
    source, // 'vendor', 'warehouse', 'transit', 'store'
    unitPrice: price,
    totalValue: price ? price * quantity : undefined,
    status: 'completed',
    createdAt: createdAt || new Date().toISOString(),
  };
}

